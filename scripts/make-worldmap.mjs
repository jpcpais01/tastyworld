// Rasterises Natural Earth land into the coarse grid used by the travel map (src/data/worldmap.ts).
// Usage: npm run worldmap (installs world-atlas + topojson-client without saving them, then runs this on land-50m.json)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const require = createRequire(resolve(process.argv[2]));
const { feature } = require('topojson-client');
const topo = JSON.parse(readFileSync(resolve(process.argv[2]), 'utf8'));
const land = feature(topo, topo.objects.land);

const COLS = 144, LAT0 = 81, LAT1 = -59, CELL = 360 / COLS, ROWS = Math.round((LAT0 - LAT1) / CELL);
const polys = [];
for (const f of land.features) {
  const g = f.geometry;
  for (let p of g.type === 'Polygon' ? [g.coordinates] : g.coordinates) {
    // Eurasia and Wrangel Island are cut at the antimeridian: move their western parts east of 180° so the rings stay simple
    if (p[0].some(([x]) => x < -179) && p[0].some(([x]) => x > 179)) p = p.map((r) => r.map(([x, y]) => [x < -150 ? x + 360 : x, y]));
    let x0 = 180, x1 = -180, y0 = 90, y1 = -90;
    for (const [x, y] of p[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
    polys.push({ rings: p, box: [x0, y0, x1, y1] });
  }
}
const inRing = (r, x, y) => {
  let c = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const inLand = (x, y) => polys.some(({ rings, box }) => x >= box[0] && x <= box[2] && y >= box[1] && y <= box[3] && inRing(rings[0], x, y) && !rings.slice(1).some((h) => inRing(h, x, y)));
const isLand = (x, y) => inLand(x, y) || inLand(x + 360, y);

// The coarse grid loses small islands and peninsulas the game cares about: keep these as land
const KEEP = [[33, 131], [36.2, 138.2], [35, 136.5], [37, 139], [38.5, 140], [34.4, 132.5], [34.8, 135.3], [35.3, 137.2], [35.7, 139.7], [37.5, 140.2], [39.5, 140.8], [41, 141], [43, 141.5], [43.6, 143.5], [40.85, 14.27], [41.01, 28.98]];
const keep = new Set(KEEP.map(([la, lo]) => `${Math.floor((LAT0 - la) / CELL)},${Math.floor((lo + 180) / CELL)}`));
const rows = [];
for (let r = 0; r < ROWS; r++) {
  let s = '';
  for (let c = 0; c < COLS; c++) {
    let n = 0;
    for (let a = 0; a < 3; a++) for (let b = 0; b < 3; b++) n += isLand(-180 + (c + (a + 0.5) / 3) * CELL, LAT0 - (r + (b + 0.5) / 3) * CELL) ? 1 : 0;
    s += n >= 3 || keep.has(`${r},${c}`) ? '#' : '.';
  }
  rows.push(s);
}
const out = `// Generated by scripts/make-worldmap.mjs from Natural Earth land (public domain). Do not edit by hand.
/** Land mask for the travel map: ${COLS} columns of ${CELL}° from 180°W, ${ROWS} rows from ${LAT0}°N down to ${LAT1}°. */
export const WORLD = {
  cols: ${COLS},
  rows: ${ROWS},
  lat0: ${LAT0},
  cell: ${CELL},
  land: [
${rows.map((r) => `    '${r}',`).join('\n')}
  ],
};
`;
writeFileSync(new URL('../src/data/worldmap.ts', import.meta.url), out);
console.log(rows.join('\n'));
